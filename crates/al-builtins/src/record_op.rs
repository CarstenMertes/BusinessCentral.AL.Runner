#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn names_round_trip_and_are_unique() {
        for op in RecordOp::ALL {
            assert_eq!(RecordOp::from_name(op.name()), Some(op));
            assert_eq!(op.to_string(), op.name());
        }
        let mut names: Vec<&str> = RecordOp::ALL.iter().map(|o| o.name()).collect();
        names.sort_unstable();
        names.dedup();
        assert_eq!(names.len(), RecordOp::ALL.len());
        assert_eq!(RecordOp::from_name("NoSuchMethod"), None);
    }
}
