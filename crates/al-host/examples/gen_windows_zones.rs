//! Generates `src/windows_zones.rs` from Unicode CLDR `windowsZones.xml` (ADR-038 amendment 2026-10-17).
//!
//! `cargo run -p al-host --example gen_windows_zones -- PATH/windowsZones.xml CLDR_VERSION > crates/al-host/src/windows_zones.rs`
//!
//! The source for the committed table is
//! `https://raw.githubusercontent.com/unicode-org/cldr/release-48/common/supplemental/windowsZones.xml`
//! (version argument `release-48`). Only the rows with `territory="001"` are used: they are the zone a Windows id maps to
//! when no country is known, which is what .NET on Linux asks ICU for. The data is under the Unicode License v3; the text
//! is in `THIRD-PARTY-UNICODE.txt`.

use std::collections::BTreeMap;

fn attr<'a>(line: &'a str, name: &str) -> Option<&'a str> {
    let key = format!("{name}=\"");
    let start = line.find(&key)? + key.len();
    let end = line[start..].find('"')? + start;
    Some(&line[start..end])
}

fn main() {
    let mut args = std::env::args().skip(1);
    let path = args
        .next()
        .expect("usage: gen_windows_zones WINDOWSZONES.XML CLDR_VERSION");
    let version = args
        .next()
        .expect("usage: gen_windows_zones WINDOWSZONES.XML CLDR_VERSION");
    let xml = std::fs::read_to_string(path).expect("read windowsZones.xml");
    let mut map: BTreeMap<String, String> = BTreeMap::new();
    for line in xml.lines().filter(|l| l.contains("<mapZone ")) {
        if attr(line, "territory") != Some("001") {
            continue;
        }
        let (other, ty) = (attr(line, "other").unwrap(), attr(line, "type").unwrap());
        // `type` may list several ids separated by a space; the first is the canonical one.
        let first = ty.split(' ').next().unwrap();
        assert!(
            map.insert(other.to_string(), first.to_string()).is_none(),
            "duplicate {other}"
        );
    }
    println!("//! Windows time zone id -> IANA id, generated by `examples/gen_windows_zones.rs`. Do not edit.");
    println!("//!");
    println!("//! Source: Unicode CLDR {version}, `common/supplemental/windowsZones.xml`, rows with territory 001.");
    println!("//! License: Unicode License v3 (see `THIRD-PARTY-UNICODE.txt`).");
    println!();
    println!("pub const CLDR_VERSION: &str = \"{version}\";");
    println!();
    println!("/// Sorted by Windows id.");
    println!("pub const WINDOWS_ZONES: &[(&str, &str)] = &[");
    for (w, i) in &map {
        println!("    (\"{w}\", \"{i}\"),");
    }
    println!("];");
}
