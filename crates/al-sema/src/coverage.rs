//! The corpus coverage map (issue 52): for every builtin overload of the catalog, whether code of the
//! counted apps calls it, as the checker resolved the call (an overload counts only when the checker picked
//! that exact overload), with one call site (`file:line`, the first in file and source order).

use crate::check::{CheckResult, Res};
use crate::workspace::Workspace;
use al_builtins::catalog::Catalog;
use serde::Serialize;
use std::collections::BTreeMap;

#[derive(Debug, Serialize)]
pub struct Overload {
    /// The method id (`Text.PadLeft#2`).
    pub id: String,
    /// The catalog line (`Text.PadLeft inst (Count: Integer, ?Char: Char) -> Text`).
    pub signature: String,
    /// One call site in a counted app, `path:line`; `None` when no counted code calls it.
    pub call: Option<String>,
}

#[derive(Debug, Serialize)]
pub struct TypeCoverage {
    /// The documented type the methods belong to (`Record`, `Text`, `System`).
    pub receiver: String,
    pub overloads: Vec<Overload>,
}

impl TypeCoverage {
    pub fn pinned(&self) -> usize {
        self.overloads.iter().filter(|o| o.call.is_some()).count()
    }
}

#[derive(Debug, Serialize)]
pub struct CoverageMap {
    pub types: Vec<TypeCoverage>,
}

impl CoverageMap {
    pub fn total(&self) -> usize {
        self.types.iter().map(|t| t.overloads.len()).sum()
    }

    pub fn pinned(&self) -> usize {
        self.types.iter().map(TypeCoverage::pinned).sum()
    }

    /// The Markdown report: a total, per-type counts, then the overloads no counted code calls.
    pub fn markdown(&self, corpus_commit: &str) -> String {
        let mut out = String::new();
        out.push_str("# Corpus coverage of the builtin methods\n\n");
        out.push_str(&format!(
            "Generated by `al-test-cli --coverage-map` from corpus commit `{corpus_commit}` (do not edit by hand). \
             An overload is pinned when a corpus test calls it and the checker resolves the call to that exact \
             overload.\n\n"
        ));
        out.push_str(&format!(
            "Total: {} of {} overloads pinned ({:.1}%).\n\n",
            self.pinned(),
            self.total(),
            pct(self.pinned(), self.total())
        ));
        out.push_str("| Type | Pinned | Overloads | % |\n|---|---:|---:|---:|\n");
        for t in &self.types {
            out.push_str(&format!(
                "| {} | {} | {} | {:.0}% |\n",
                t.receiver,
                t.pinned(),
                t.overloads.len(),
                pct(t.pinned(), t.overloads.len())
            ));
        }
        out.push_str("\n## Unpinned overloads\n");
        for t in &self.types {
            let missing: Vec<&Overload> = t.overloads.iter().filter(|o| o.call.is_none()).collect();
            if missing.is_empty() {
                continue;
            }
            out.push_str(&format!(
                "\n### {} ({} of {} unpinned)\n\n",
                t.receiver,
                missing.len(),
                t.overloads.len()
            ));
            for o in missing {
                out.push_str(&format!("- `{}`: `{}`\n", o.id, o.signature));
            }
        }
        out
    }
}

fn pct(a: usize, b: usize) -> f64 {
    if b == 0 { 0.0 } else { 100.0 * a as f64 / b as f64 }
}

/// The map for `catalog`, counting calls in the files of the apps `counted` (indices into `ws.apps`).
pub fn coverage(ws: &Workspace, checked: &CheckResult, catalog: &Catalog, counted: &[usize]) -> CoverageMap {
    // The first call site of each id: (path, line), smallest in path and line order.
    let mut first: BTreeMap<String, (String, usize)> = BTreeMap::new();
    let mut by_file: BTreeMap<usize, Vec<(u32, String)>> = BTreeMap::new();
    for (key, res) in checked.resolutions.iter() {
        if let Res::Builtin(id) = res {
            let file = key.0 as usize;
            if counted.contains(&ws.files[file].app) {
                by_file.entry(file).or_default().push((key.1 as u32, id.clone()));
            }
        }
    }
    for (file, mut calls) in by_file {
        let f = &ws.files[file];
        let text = &ws.apps[f.app].files[f.file_in_app].1;
        calls.sort();
        for (offset, id) in calls {
            let line = text[..(offset as usize).min(text.len())].matches('\n').count() + 1;
            let site = (f.path.clone(), line);
            first
                .entry(id)
                .and_modify(|s| {
                    if site < *s {
                        *s = site.clone();
                    }
                })
                .or_insert(site);
        }
    }
    let mut types: BTreeMap<String, Vec<Overload>> = BTreeMap::new();
    for sig in &catalog.signatures {
        let id = catalog.id(sig);
        let call = first.get(&id).map(|(p, l)| format!("{p}:{l}"));
        types.entry(sig.receiver.clone()).or_default().push(Overload {
            id,
            signature: sig.to_line(),
            call,
        });
    }
    CoverageMap {
        types: types
            .into_iter()
            .map(|(receiver, mut overloads)| {
                overloads.sort_by(|a, b| a.id.cmp(&b.id));
                TypeCoverage { receiver, overloads }
            })
            .collect(),
    }
}
